// Vireo Bay — a small seeded random source, so the same seed always builds the
// same city and plays the same shots. Nothing in the simulation uses Math.random.

/** Mulberry32: fast, deterministic, good enough for a game world. */
export function createRandom(seed) {
  let state = (seed >>> 0) || 0x9e3779b9;
  function next() {
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  }
  return {
    next,
    /** Float in [min, max). */
    range(min, max) {
      return min + next() * (max - min);
    },
    /** Integer in [min, max] inclusive. */
    int(min, max) {
      return min + Math.floor(next() * (max - min + 1));
    },
    /** One element of a non-empty array. */
    pick(list) {
      return list[Math.floor(next() * list.length)];
    },
    /** True with probability p (0..1). */
    chance(p) {
      return next() < p;
    },
    /** A fresh seed derived from this stream. */
    fork() {
      return Math.floor(next() * 4294967296);
    },
  };
}
